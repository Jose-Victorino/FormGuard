function getHeatmapColor(frequency) {
  if(frequency === 0) return

  if(frequency < 0.25)
    return "hsl(50, 87%, 55%)"

  if(frequency < 0.5)
    return "hsl(36, 94%, 50%)"

  return "hsl(0, 76%, 50%)"
}

